-- Errors caught by pcall: messages with and without positions, and other values.
print(pcall(error, "plain"))
print(pcall(error, "no position", 0))
print(pcall(function() error("level one") end))
print(pcall(function() error("level two", 2) end))
print(pcall(function() error() end))
print(pcall(function() error(42) end))
print(pcall(function() error(false) end))
print(pcall(function() return "fine", 2 end))
print(pcall(pcall, error, "nested"))
print(pcall(assert, true, "kept"))
print(pcall(assert, false))
print(pcall(assert, nil, "message"))
print(pcall(assert))
print(select('#', pcall(error)))
